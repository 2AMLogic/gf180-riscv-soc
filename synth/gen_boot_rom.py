#!/usr/bin/env python3
"""Generate synth/boot_rom_const.v: the boot ROM as constants, for synthesis.

The stamped rtl/common/boot_rom.sv is a behavioural array filled by
$readmemh and a plusarg, which the Yosys front end cannot elaborate and which
spec/soc.md says a synthesis flow replaces with a generated standard-cell ROM.
This emits a module with the same name and ports whose contents are a case
table of the image in firmware/boot/boot_rom.hex (the image the boot test
runs), registered one cycle like the original. The stamped file is not edited.

    gen_boot_rom.py <boot_rom.hex> <out.v>
"""
import re
import sys

words = [int(l, 16) for l in open(sys.argv[1]).read().split() if re.fullmatch(r"[0-9a-fA-F]{8}", l)]
assert len(words) == 1024, f"expected 1024 words, got {len(words)}"
out = [
    "// GENERATED by synth/gen_boot_rom.py from firmware/boot/boot_rom.hex; do not edit.",
    "// Synthesis replacement for rtl/common/boot_rom.sv: same module name and ports,",
    "// the image as constants, one-cycle synchronous read.",
    "module boot_rom #(",
    '    parameter INIT_FILE = "unused"',
    ") (",
    "    input  wire        clk_i,",
    "    input  wire        req_i,",
    "    input  wire [11:2] addr_i,",
    "    output reg  [31:0] rdata_o",
    ");",
    "  reg [31:0] word;",
    "  always @* begin",
    "    case (addr_i)",
]
out += [f"      10'd{i}: word = 32'h{w:08x};" for i, w in enumerate(words)]
out += [
    "      default: word = 32'h0;",
    "    endcase",
    "  end",
    "  always @(posedge clk_i) if (req_i) rdata_o <= word;",
    "endmodule",
]
open(sys.argv[2], "w").write("\n".join(out) + "\n")
